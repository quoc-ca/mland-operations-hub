CREATE TABLE member_workshop_booking_quotes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    quote_ref CHAR(36) NOT NULL,
    member_account_id BIGINT UNSIGNED NOT NULL,
    package_id BIGINT UNSIGNED NOT NULL,
    package_name_snapshot LONGTEXT NOT NULL,
    price_per_participant BIGINT NOT NULL,
    participant_count INT NOT NULL,
    session_facts_json JSON NOT NULL,
    benefit_selection_json JSON NOT NULL,
    gross_amount BIGINT NOT NULL,
    program_discount BIGINT NOT NULL,
    points_used BIGINT NOT NULL,
    point_discount BIGINT NOT NULL,
    post_promotion_amount BIGINT NOT NULL,
    earn_base BIGINT NOT NULL,
    terms_digest VARCHAR(128) NOT NULL,
    quote_state VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    accepted_booking_code VARCHAR(32) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_mwbq_quote_ref (quote_ref),
    KEY idx_mwbq_member_state (member_account_id, quote_state, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
